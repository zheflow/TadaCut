// Saves the promo's four shots as the server's sample-project artwork, so the
// "城市漫游" sample in the app and the promo share one drawing.
//
//   npm run sample-art   → apps/server/src/sample-art.ts
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { Shot } from "./src/art";

/** The shots as standalone SVG documents at their first frame; the ridge
 * shot keeps the hiker that walks through the promo's reframing demo. */
export const renderSampleArt = () =>
  [0, 1, 2, 3].map((variant) =>
    renderToStaticMarkup(
      createElement(Shot, {
        id: "s",
        t: 0,
        variant,
        walker: variant === 1 ? 900 : undefined,
        file: true,
      }),
    ),
  );

if (fileURLToPath(import.meta.url) === path.resolve(process.argv[1] ?? "")) {
  const out = path.resolve("apps/server/src/sample-art.ts");
  const art = renderSampleArt();
  await fs.writeFile(
    out,
    `// Generated by \`npm run sample-art\` from promo/src/art.tsx; do not edit.
// The four shots of the "城市漫游" sample project, frozen at their first frame.
export const sampleArt: readonly string[] = ${JSON.stringify(art, null, 2)};
`,
  );
  console.log(
    `${out} · ${art.map((svg) => `${(svg.length / 1024).toFixed(0)} KB`).join(" / ")}`,
  );
}
